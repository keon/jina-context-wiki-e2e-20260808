assert_builds_preserved() {
  local before="$1" after="$2"
  [[ -z "$before" ]] && return 0
  # shellcheck disable=SC2016 # `${build.id}` belongs to the JavaScript program.
  BEFORE_BUILDS="$before" AFTER_BUILDS="$after" node -e '
const before = JSON.parse(process.env.BEFORE_BUILDS).builds ?? [];
const after = new Map((JSON.parse(process.env.AFTER_BUILDS).builds ?? []).map(build => [build.id, build]));
for (const build of before.filter(build => build.status !== "completed")) {
  if (!after.has(build.id)) throw new Error(`in-flight/failed build disappeared across restart: ${build.id}`);
}
'
}

print_build_observability() {
  local builds="$1" api_port="$2" observations
  observations="$(BUILDS_PAYLOAD="$builds" node -e '
const builds = JSON.parse(process.env.BUILDS_PAYLOAD).builds ?? [];
for (const build of builds.filter(build => build.status === "active" || build.status === "failed").slice(0, 10)) {
  console.log([build.id, build.status, build.repository, build.ref].join("\t"));
}
')"
  if [[ -z "$observations" ]]; then
    echo "No active or failed build exists; the persisted Board catalog is reachable."
    return 0
  fi
  echo "Observable resumable/diagnostic builds:"
  while IFS=$'\t' read -r build_id status repository ref; do
    local progress
    progress="$(curl -fsS \
      "http://127.0.0.1:$api_port/wiki/builds/$(urlencode "$build_id")/progress" \
      -H "authorization: Bearer $JINA_RESTART_INTERNAL_TOKEN" \
      -H "x-jina-tenant-id: $JINA_RESTART_TENANT" \
      -H "x-jina-principal-id: tenant:$JINA_RESTART_TENANT")"
    BUILD_PROGRESS="$progress" node -e 'JSON.parse(process.env.BUILD_PROGRESS)'
    echo "  $build_id  $status  $repository@$ref"
    echo "    source $JINA_RESTART_ENV_FILE"
    echo "    scripts/context-build.sh --watch $build_id"
  done <<<"$observations"
}

