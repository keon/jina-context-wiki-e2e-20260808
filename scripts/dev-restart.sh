resolve_migration_restart_metadata() {
  if [[ -n "${JINA_RESTART_MIGRATION_DATABASE_URL:-}" &&
    -n "${JINA_RESTART_RUNTIME_DB_USER:-}" ]]; then
    return 0
  fi
  # Restart files created before migration metadata was persisted can still
  # upgrade the one fixed default local stack. Never guess credentials for a
  # customized database; a fresh dev-up/capture must record those explicitly.
  if [[ "${JINA_RESTART_DATABASE_URL:-}" == \
    "postgres://jina_runtime:dev-runtime@127.0.0.1:55480/jina_dev" ]]; then
    JINA_RESTART_MIGRATION_DATABASE_URL="postgres://jina_app:dev-migration@127.0.0.1:55480/jina_dev"
    JINA_RESTART_RUNTIME_DB_USER="jina_runtime"
    return 0
  fi
  echo "Restart state predates retained migration metadata; run scripts/dev-up.sh again." >&2
  return 1
}

