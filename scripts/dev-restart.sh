update_shell_export_file() {
  local file="$1" variable="$2" value="$3" temporary replacement
  [[ "$variable" =~ ^[A-Z][A-Z0-9_]*$ ]] || {
    echo "Refusing invalid local environment variable name: $variable" >&2
    return 2
  }
  [[ "$value" =~ ^(tenant:[0-9a-f-]{36}|user:[^[:space:]@]+@[^[:space:]@]+)$ ]] || {
    echo "Refusing invalid local Context principal value." >&2
    return 2
  }
  temporary="$(mktemp "$file.query-principal.XXXXXX")"
  replacement="export $variable=$value"
  if ! awk -v prefix="export $variable=" -v replacement="$replacement" '
    index($0, prefix) == 1 {
      if (!replaced) {
        print replacement
        replaced = 1
      }
      next
    }
    { print }
    END {
      if (!replaced) print replacement
    }
  ' "$file" >"$temporary"; then
    rm -f -- "$temporary"
    return 1
  fi
  chmod 600 "$temporary"
  mv "$temporary" "$file"
}

assert_retained_database_targets() {
  RUNTIME_DATABASE_URL="$1" \
    MIGRATION_DATABASE_URL="$2" \
    EXPECTED_PGPORT="$3" \
    EXPECTED_RUNTIME_USER="$4" \
    python3 - <<'PY'
import os
import urllib.parse

runtime = urllib.parse.urlsplit(os.environ["RUNTIME_DATABASE_URL"])
migration = urllib.parse.urlsplit(os.environ["MIGRATION_DATABASE_URL"])
expected_port = int(os.environ["EXPECTED_PGPORT"])
expected_runtime_user = os.environ["EXPECTED_RUNTIME_USER"]

def scope(label, parsed):
    if parsed.scheme not in {"postgres", "postgresql"}:
        raise SystemExit(f"{label} connection is not PostgreSQL")
    if parsed.hostname not in {"127.0.0.1", "localhost"}:
        raise SystemExit(f"{label} connection does not target retained local PostgreSQL")
    if parsed.port != expected_port:
        raise SystemExit(f"{label} connection does not use the retained PostgreSQL port")
    database = parsed.path.removeprefix("/")
    if not database or "/" in database:
        raise SystemExit(f"{label} connection has an invalid database name")
    if not parsed.username or parsed.password is None:
        raise SystemExit(f"{label} connection lacks private login credentials")
    return parsed.port, database

runtime_scope = scope("runtime", runtime)
migration_scope = scope("migration", migration)
if runtime_scope != migration_scope:
    raise SystemExit("runtime and migration connections do not target the same retained PostgreSQL database")
if runtime.username != expected_runtime_user:
    raise SystemExit("runtime connection login does not match retained runtime role metadata")
if migration.username == runtime.username:
    raise SystemExit("migration connection must use a distinct non-runtime login")
PY
}

